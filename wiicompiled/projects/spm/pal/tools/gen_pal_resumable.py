"""Generate projects/spm/pal/resumable_functions.inc from the USA list (projects/spm/resumable_functions.inc).

The USA list holds USA guest addresses; the PAL dol (R8PP01) moved most functions. Each address is mapped through
addr_map.tsv (gen_addr_map.py) the same way make_pal_runtime.py maps literals: a symbol-exact row maps directly.
Addresses whose neighbours disagree (inside big unnamed fn_ blobs) are NOT guessed: they are written commented out with
UNVERIFIED so the translator never marks a wrong PAL function as resumable. Review those by hand against the PAL dol.

Usage: python3 gen_pal_resumable.py [<wiicompiled dir>]   (default: the directory two levels above this file's dir)
"""
import bisect, re, sys
from pathlib import Path

WC = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[3]
rows = [l.split("\t") for l in (WC / "projects/spm/pal/addr_map.tsv").read_text().splitlines()
        if l and not l.startswith("#")]
starts = [int(r[0], 16) for r in rows]
eus = [int(r[1], 16) for r in rows]
sizes = [int(r[2], 16) for r in rows]
names = [r[3].strip() for r in rows]
LINE = re.compile(r"^\s*(0x[0-9A-Fa-f]{8})\s*,\s*//\s*(\S+)")


def map_addr(a):
    i = bisect.bisect_right(starts, a) - 1
    if i >= 0 and a < starts[i] + max(sizes[i], 4):
        return eus[i] + (a - starts[i]), "symbol", names[i]
    if i >= 0:
        prev = eus[i] - starts[i]
        if i + 1 < len(starts) and eus[i + 1] - starts[i + 1] == prev:
            return a + prev, "shift", names[i]
    return None, "unsure", names[i] if i >= 0 else ""


out = ["// PAL (R8PP01) resumable functions: the PAL twin of ../resumable_functions.inc.",
       "// GENERATED by projects/spm/pal/tools/gen_pal_resumable.py: edit that script or addr_map.tsv, not this file.",
       "// Read by the PAL translator (build-region.py translate) and by the PAL runtime (make_pal_runtime.py rewrites",
       "// save_state.cpp to include this file).",
       ""]
for raw in (WC / "projects/spm/resumable_functions.inc").read_text().splitlines():
    m = LINE.match(raw)
    if not m:
        continue
    us, label = int(m.group(1), 16), m.group(2)
    eu, how, sym = map_addr(us)
    if eu is None or how == "unsure":
        out.append(f"// UNVERIFIED (USA {us:#010x} {label}: nearest map row {sym} disagrees): fix by hand from the PAL dol")
        out.append(f"// {us:#010x},  // {label}")
    else:
        out.append(f"0x{eu:08X},  // {label} (USA {us:#010x}, {how} {sym})")
(WC / "projects/spm/pal/resumable_functions.inc").write_text("\n".join(out) + "\n")
print("\n".join(out))
